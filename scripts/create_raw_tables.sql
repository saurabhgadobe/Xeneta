CREATE SCHEMA IF NOT EXISTS raw;

CREATE TABLE IF NOT EXISTS raw.load_batches (
    BATCH_ID VARCHAR NOT NULL,
    TABLE_NAME VARCHAR NOT NULL,
    SOURCE_FILE VARCHAR NOT NULL,
    ROW_COUNT BIGINT NOT NULL,
    LOADED_AT TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (BATCH_ID, TABLE_NAME)
);

CREATE TABLE IF NOT EXISTS raw.ports (
    PID VARCHAR,
    CODE VARCHAR,
    SLUG VARCHAR,
    NAME VARCHAR,
    COUNTRY VARCHAR,
    COUNTRY_CODE VARCHAR,
    BATCH_ID VARCHAR NOT NULL,
    SOURCE_FILE VARCHAR NOT NULL,
    INGESTED_AT TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS raw.regions (
    SLUG VARCHAR,
    NAME VARCHAR,
    PARENT VARCHAR,
    BATCH_ID VARCHAR NOT NULL,
    SOURCE_FILE VARCHAR NOT NULL,
    INGESTED_AT TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS raw.exchange_rates (
    DAY VARCHAR,
    CURRENCY VARCHAR,
    RATE VARCHAR,
    BATCH_ID VARCHAR NOT NULL,
    SOURCE_FILE VARCHAR NOT NULL,
    INGESTED_AT TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS raw.datapoints (
    D_ID VARCHAR,
    CREATED VARCHAR,
    ORIGIN_PID VARCHAR,
    DESTINATION_PID VARCHAR,
    VALID_FROM VARCHAR,
    VALID_TO VARCHAR,
    COMPANY_ID VARCHAR,
    SUPPLIER_ID VARCHAR,
    EQUIPMENT_ID VARCHAR,
    BATCH_ID VARCHAR NOT NULL,
    SOURCE_FILE VARCHAR NOT NULL,
    INGESTED_AT TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS raw.charges (
    D_ID VARCHAR,
    CURRENCY VARCHAR,
    CHARGE_VALUE VARCHAR,
    BATCH_ID VARCHAR NOT NULL,
    SOURCE_FILE VARCHAR NOT NULL,
    INGESTED_AT TIMESTAMPTZ NOT NULL
);
